import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { ECONOMIC_FIELD_COVERAGE, legacyMarketDataRouter } from './routers/legacyMarketData';

const root = resolve(import.meta.dirname, '..');
const read = (path: string) => readFileSync(resolve(root, path), 'utf8');
const directory = read('client/src/components/econ/EconomicFieldSourceDirectory.tsx');
const preservedRoute = read('client/src/components/econ/EconomicDataHubPreservedRoute.tsx');
const legacyWorkspace = read('client/src/components/LegacyMarketDataWorkspace.tsx');
const auditPanel = read('client/src/components/LegacyFieldAccessAuditPanel.tsx');
const officialObservations = read('client/src/components/econ/EconomicCalendarOfficialObservations.tsx');
const officialService = read('server/economicCalendarOfficialData.ts');
const schema = read('drizzle/schema.ts');
const terminal = read('client/src/pages/Terminal.tsx');

describe('经济字段来源目录与遗留字段授权遮蔽', () => {
  it('经济目录逐字段声明公开来源与未接入边界，不把原工作区静态字段标为已核验', () => {
    expect(ECONOMIC_FIELD_COVERAGE.map((field) => field.field)).toEqual(expect.arrayContaining(['美联储总资产', '准备金余额', '有效联邦基金利率', '宏观事件实际值、前值和预期', '就业、通胀、PMI 与 GDP 原始读数']));
    expect(ECONOMIC_FIELD_COVERAGE.filter((field) => field.state === 'true_empty')).toHaveLength(3);
    expect(directory).toContain('<BusinessTerm');
    expect(directory).toContain('悬浮或键盘聚焦字段名称');
    expect(directory).toContain('不以历史保留数字或样例目录替代');
    expect(preservedRoute).toContain('data-preserved-economic-hub="true"');
    expect(preservedRoute).toContain('<EconomicDataHub />');
    expect(preservedRoute).not.toContain('<EconomicCalendarOfficialObservations />');
    expect(preservedRoute).toContain('<ModuleLiveDeliveryTable {...openBBDelivery}');
    expect(terminal).toMatch(/<EconomicFieldSourceBoundary>\s*\{econPanel\.component\}\s*<\/EconomicFieldSourceBoundary>/);
    expect(terminal).toMatch(/<EconomicFieldSourceBoundary>\s*<EconomicDashboard title="经济数据及分析" \/>\s*<\/EconomicFieldSourceBoundary>/);
    expect(officialObservations).toContain('getEconomicCalendarOfficialObservations');
    expect(officialService).toContain('LNS14000000');
    expect(officialService).toContain('CES0000000001');
    expect(officialService).toContain('CUUR0000SA0');
    expect(officialService).toContain('JTS000000000000000JOL');
    expect(officialService).toContain('FED_INDPRO');
    expect(officialService).toContain('fetchFred');
    expect(officialService).toContain('points.slice(0, 12)');
    expect(officialService).toContain('BOJ_CORE_CPI_EX_FRESH_SPECIAL');
    expect(officialService).toContain('BOJ_CORE_CPI_EX_FRESH_ENERGY_SPECIAL');
    expect(officialService).toContain('BOJ_CORE_CPI_EX_FOOD_ENERGY_SPECIAL');
    expect(officialService).toContain('BOJ_M2_MONEY_STOCK');
    expect(officialService).toContain('BOJ_M3_MONEY_STOCK');
    expect(officialService).toContain('ONS_GDP_MONTHLY_INDEX');
    expect(officialService).toContain('ONS_EMPLOYMENT_16_PLUS');
    expect(officialService).toContain('ONS_UNEMPLOYMENT_RATE_16_PLUS');
    expect(officialService).toContain('ONS_AWE_TOTAL_PAY');
    expect(officialService).toContain('ONS_AWE_REGULAR_PAY');
    expect(officialService).toContain('fetchBojCoreCpi');
    expect(officialService).toContain('fetchOnsCsv');
    expect(officialService).toContain('fetchOnsEarnings');
    expect(officialService).toContain('MAM1NAM3M3MO');
    expect(officialService).toContain("'3. AWE Regular Pay'");
    expect(officialService).toContain("'economic-activity') === (unemployment ? 'unemployed' : 'in-employment')");
    expect(officialService).toContain("'sic-unofficial') === 'A--T'");
    expect(officialService).toContain("unemployment ? 'unemployed' : 'in-employment'");
    expect(officialService).toContain('selectHistory');
    expect(officialService).toContain("region: '美国'");
    expect(officialService).toContain("region: '欧元区'");
    expect(officialService).toContain("region: '欧盟'");
    expect(officialService).toContain('prc_hicp_manr');
    expect(officialService).toContain('nama_10_gdp');
    expect(officialService).toContain('sts_trtu_m');
    expect(officialService).toContain('ext_st_eu27_2020sitc');
    expect(officialObservations).toContain('data-economic-calendar-analysis="true"');
    expect(officialObservations).toContain('data-calendar-analysis-view="coverage-matrix"');
    expect(officialObservations).toContain('data-calendar-analysis-view="change-ledger"');
    expect(officialObservations).toContain('data-calendar-analysis-view="source-lineage"');
    expect(officialObservations).toContain('观测版图');
    expect(officialObservations).toContain('变化账本');
    expect(officialObservations).toContain('来源谱系');
    expect(officialObservations).toContain('同字段');
    expect(officialObservations).toContain('sourceBoundary');
    expect(schema).toContain('economicCalendarAnomalyRules');
    expect(schema).toContain('economicCalendarRegionPresets');
    expect(schema).toContain('economicTrendWindowPresets');
    expect(schema).toContain('economic_trend_window_preset_user_name_uq');
    expect(schema).toContain('lastUsedAt');
    expect(schema).toContain('economic_trend_window_preset_user_last_used_idx');
    expect(schema).toContain('japan-cpi-money');
    expect(schema).toContain('uk-pay');
  });

  it('遗留字段遮蔽仅在账户授权后展示数值、历史路径和终端内来源摘录', () => {
    expect(schema).toContain('legacyFieldAccessGrants');
    expect(schema).toContain('legacy_field_access_user_source_uq');
    expect(legacyWorkspace).toContain("grant?.status === 'authorized'");
    expect(legacyWorkspace).toContain('字段已遮蔽');
    expect(legacyWorkspace).toContain('申请解锁');
    expect(legacyWorkspace).toContain('管理员授权队列');
    expect(legacyWorkspace).toContain('enabled: !!sourceId && selectedAuthorized');
    expect(schema).toContain('legacyFieldAccessAuditEvents');
    expect(auditPanel).toContain('legacy-field-access-audit-');
    expect(auditPanel).toContain('公式注入');
  });

  it('授权读取、申请、管理员队列和审批均保留受保护路由边界', async () => {
    const caller = legacyMarketDataRouter.createCaller({} as never);
    await expect(caller.listLegacyFieldAccess()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.requestLegacyFieldAccess({ sourceId: 'SP500' })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.listLegacyFieldAccessRequests()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.decideLegacyFieldAccess({ grantId: 1, status: 'authorized' })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.listLegacyFieldAccessAudit()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.getResearchPathAccess()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.toggleResearchPathFavorite({ pathId: 'energy-fx-policy' })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.shareResearchPath({ pathId: 'energy-fx-policy', sharedWithUserId: 1 })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.listResearchPathNotes({ pathId: 'energy-fx-policy', ownerUserId: 1 })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.createResearchPathNote({ pathId: 'energy-fx-policy', ownerUserId: 1, body: '匿名不得创建备注' })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.reviewResearchPathNote({ noteId: 1, status: 'confirmed' })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.listEconomicCalendarAnomalyRules()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.saveEconomicCalendarAnomalyRule({ seriesId: 'BLS_CES0000000001', threshold: 1, isActive: true })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.checkEconomicCalendarAnomalyAlerts()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.listEconomicCalendarRegionPresets()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.saveEconomicCalendarRegionPreset({ name: '美国观察', region: 'us' })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.listEconomicTrendWindowPresets()).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.saveEconomicTrendWindowPreset({ name: '日本窗口', region: 'japan', topic: 'japan-cpi-money', startDate: '2025-01-01', endDate: '2025-12-31' })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.deleteEconomicTrendWindowPreset({ id: 1 })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.markEconomicTrendWindowPresetUsed({ id: 1 })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
    await expect(caller.deleteInactiveEconomicTrendWindowPresets({ ids: [1], inactiveDays: 90 })).rejects.toMatchObject({ code: 'UNAUTHORIZED' });
  });
});
